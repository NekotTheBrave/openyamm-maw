#!/usr/bin/env python3
"""Writes game/app/SettingsShippedDefaults.inc: every settings value that a release shipped as a default.

Releases up to 1.5 shipped settings templates (settings_release.ini for desktop and the Flatpak,
android/settings.ini for Android), and the game wrote every key on every start. A player's file therefore cannot
tell their choices from the defaults they were given. The one-time conversion to sparse settings files
(migrateGameSettings, settings profile version 5) drops each key whose value equals a default its platform shipped:
one of these values, or a current code default. Keys a template lacked took the code default of that release; those
defaults are unchanged since, except actor_models, which an earlier migration already forces.

The templates no longer exist after the last listed commit, so the output is final unless a ref is added.
"""

import argparse
import subprocess
import sys
from pathlib import Path

REFS = ["1.0", "1.1", "1.2", "1.3", "1.4", "1.5",
        "4af3efd837e2d3a63dee646cec83a7ea35d45a7f"]  # The last commit with templates.
TEMPLATES = {"desktop": "settings_release.ini", "android": "android/settings.ini"}


def parse_ini(text):
    section = "global"
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped[0] in ";#":
            continue
        if len(stripped) >= 3 and stripped[0] == "[" and stripped[-1] == "]":
            section = stripped[1:-1].strip().lower()
            continue
        if "=" in stripped:
            key, value = stripped.split("=", 1)
            key = key.strip().lower()
            if key:
                yield section, key, value.strip()


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    output = args.output or args.repo / "game/app/SettingsShippedDefaults.inc"

    values = set()
    for ref in REFS:
        for platform, path in TEMPLATES.items():
            text = subprocess.run(["git", "-C", str(args.repo), "show", f"{ref}:{path}"],
                                  check=True, capture_output=True, text=True).stdout
            for section, key, value in parse_ini(text):
                # Profiles are state and asset roots are install paths; neither is a default to compare against.
                if section in ("profile", "assets"):
                    continue
                values.add((platform, section, key, value))

    lines = [
        "// Generated by tools/settings_default_history.py; do not edit.",
        "// Every value the settings templates of releases 1.0-1.5 shipped, per platform.",
        "",
        "struct ShippedSettingsValue",
        "{",
        "    const char *pPlatform;",
        "    const char *pSection;",
        "    const char *pKey;",
        "    const char *pValue;",
        "};",
        "",
        "inline constexpr ShippedSettingsValue ShippedSettingsValues[] = {",
    ]
    for platform, section, key, value in sorted(values):
        lines.append(f"    {{{cpp_string(platform)}, {cpp_string(section)}, {cpp_string(key)}, {cpp_string(value)}}},")
    lines.append("};")
    output.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(values)} values to {output}", file=sys.stderr)


if __name__ == "__main__":
    main()
